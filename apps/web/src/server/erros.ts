/** Erro de regra de negócio: vira resposta 4xx com o envelope de erro da API (GDD 9.6). */
export class ErroDominio extends Error {
  constructor(
    readonly codigo: CodigoErro,
    readonly detalhes?: Record<string, unknown>,
    mensagem?: string,
  ) {
    super(mensagem ?? MENSAGENS[codigo]);
    this.name = 'ErroDominio';
  }
}

/** Código SQLSTATE de violação de unicidade. */
export const ehViolacaoUnica = (erro: unknown): boolean =>
  typeof erro === 'object' && erro !== null && (erro as { code?: unknown }).code === '23505';
